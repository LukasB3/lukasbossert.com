// under the same ids, and the same words wherever the facts are the same. A
// change to a shared paragraph is made on all three sites.

// A part of a paragraph: text or a link.
export type Inline = string | { text: string; href: string };
// A line break inside a paragraph (an address) is a "\n".
export type Paragraph = string | Inline[];
export type Block = Paragraph | { list: Paragraph[] };

export interface Section {
  id: string;
  heading: string;
  body: Block[];
}

export interface LegalDoc {
  sections: Section[];
  updated: string;
}

